-- Operator-run migration in the explicitly selected AgentCity schema.
-- Runtime never creates schema objects. Standard PK constraints are informational.
CREATE TABLE IF NOT EXISTS AGENTCITY_OBSERVATION_FACTS_V1 (
 OWNER_ID VARCHAR NOT NULL, SIMULATION_ID VARCHAR NOT NULL, REVISION NUMBER(38,0) NOT NULL,
 TICK NUMBER(38,0) NOT NULL, FACT_ID VARCHAR NOT NULL, KIND VARCHAR NOT NULL,
 ENTITY_ID VARCHAR NOT NULL, PAYLOAD VARIANT NOT NULL, FACT_SHA256 VARCHAR NOT NULL,
 PRIMARY KEY (OWNER_ID,SIMULATION_ID,REVISION,FACT_ID)
);
CREATE TABLE IF NOT EXISTS AGENTCITY_OBSERVATION_REVISIONS_V1 (
 OWNER_ID VARCHAR NOT NULL, SIMULATION_ID VARCHAR NOT NULL, REVISION NUMBER(38,0) NOT NULL,
 TICK NUMBER(38,0) NOT NULL, SOURCE_SHA256 VARCHAR NOT NULL, FACTS_SHA256 VARCHAR NOT NULL,
 FACT_COUNT NUMBER(38,0) NOT NULL, PROVENANCE VARIANT NOT NULL,
 INGESTED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
 PRIMARY KEY (OWNER_ID,SIMULATION_ID,REVISION)
);
CREATE OR REPLACE VIEW AGENTCITY_OBSERVATIONS_V1 AS
 SELECT f.*,r.PROVENANCE,r.INGESTED_AT
 FROM AGENTCITY_OBSERVATION_FACTS_V1 f
 JOIN AGENTCITY_OBSERVATION_REVISIONS_V1 r USING(OWNER_ID,SIMULATION_ID,REVISION);
CREATE OR REPLACE VIEW AGENTCITY_OBSERVATION_AGENTS_V1 AS
 SELECT OWNER_ID,SIMULATION_ID,REVISION,TICK,ENTITY_ID,
 PAYLOAD:agent_id::VARCHAR AGENT_ID,PAYLOAD:life::VARCHAR LIFE,
 PAYLOAD:active::BOOLEAN ACTIVE,PAYLOAD:health::FLOAT HEALTH,
 PAYLOAD:trust::FLOAT TRUST,PAYLOAD:mental::FLOAT MENTAL,PAYLOAD
 FROM AGENTCITY_OBSERVATIONS_V1 WHERE KIND='agent';
CREATE OR REPLACE VIEW AGENTCITY_OBSERVATION_RELATIONSHIPS_V1 AS
 SELECT OWNER_ID,SIMULATION_ID,REVISION,TICK,ENTITY_ID,
 PAYLOAD:from_agent_id::VARCHAR FROM_AGENT_ID,PAYLOAD:to_agent_id::VARCHAR TO_AGENT_ID,
 PAYLOAD:pair_id::VARCHAR PAIR_ID,PAYLOAD:kind::VARCHAR KIND,
 PAYLOAD:trust::FLOAT TRUST,PAYLOAD:affection::FLOAT AFFECTION,
 PAYLOAD:conflict::FLOAT CONFLICT,PAYLOAD
 FROM AGENTCITY_OBSERVATIONS_V1 WHERE KIND='relationship';
CREATE OR REPLACE VIEW AGENTCITY_OBSERVATION_OPINIONS_V1 AS
 SELECT OWNER_ID,SIMULATION_ID,REVISION,TICK,ENTITY_ID,
 PAYLOAD:agent_id::VARCHAR AGENT_ID,PAYLOAD:category::VARCHAR CATEGORY,
 PAYLOAD:key::VARCHAR TOPIC,PAYLOAD:value VALUE,PAYLOAD:confidence::FLOAT CONFIDENCE,PAYLOAD
 FROM AGENTCITY_OBSERVATIONS_V1 WHERE KIND='opinion';
CREATE OR REPLACE VIEW AGENTCITY_OBSERVATION_CHANGES_V1 AS
 SELECT OWNER_ID,SIMULATION_ID,REVISION,TICK,FACT_ID,
 PAYLOAD:entity_kind::VARCHAR ENTITY_KIND,PAYLOAD:entity_id::VARCHAR ENTITY_ID,
 PAYLOAD:field::VARCHAR FIELD,PAYLOAD:before BEFORE_VALUE,PAYLOAD:after AFTER_VALUE,PAYLOAD
 FROM AGENTCITY_OBSERVATIONS_V1 WHERE KIND='change';
-- Grant the runtime role USAGE on database/schema/warehouse, SELECT on the views,
-- and SELECT/INSERT/DELETE on both tables. UPDATE is not needed: facts are immutable.
